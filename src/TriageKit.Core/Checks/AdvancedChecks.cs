/// <summary>
/// Trusted root certificates. A root that Microsoft doesn't distribute lets whoever holds its key impersonate any
/// website (HTTPS interception, as with Superfish). Roots are compared with Microsoft's trusted-root list (the
/// AuthRoot CTL Windows keeps in the registry).
/// </summary>
[SupportedOSPlatform("windows")]
public sealed class CertificateCheck : ICheck
{
    public string Name => "Root certificates";

    private static readonly (Regex Pattern, Severity Sev, string Why)[] Known =
    {
        (new(@"Superfish|eDellRoot|DSDTestProvider|Komodia|PrivDog|Lenovo.*Customer|WiFi\s*Pineapple", RegexOptions.IgnoreCase), Severity.Critical,
            "This root is known from adware or vendor scandals that let attackers read encrypted traffic."),
        (new(@"mitmproxy|Fiddler|DO_NOT_TRUST|PortSwigger|Burp|Charles Proxy|Proxyman|HTTP Toolkit|Telerik", RegexOptions.IgnoreCase), Severity.Medium,
            "A traffic-inspection tool can read all HTTPS traffic of this PC. Fine if you are a developer using it; otherwise remove it."),
        (new(@"mkcert|localhost|IIS Express|ASP\.NET Core HTTPS development|Development CA|DevCert", RegexOptions.IgnoreCase), Severity.Low,
            "Looks like a local development certificate. Remove it if you don't develop software."),
        // Local certificates apps create for themselves (game launchers talking to their own localhost service,
        // Zadig/libwdi driver installs, AutoHotkey's UI access signing).
        (new(@"libwdi autogenerated|Battle\.net Local|Electronic Arts|EA Desktop|Origin|Riot Games|AutoHotkey|Ubisoft|Steam|Razer|Corsair|Logitech|NZXT|ASUS|MSI Center|Zadig", RegexOptions.IgnoreCase), Severity.Low,
            "Looks like a certificate an app installed for its own use (game launcher, driver tool). Usually harmless; remove it if you uninstalled that app."),
        (new(@"Kaspersky|ESET|Avast|AVG|Bitdefender|Norton|Symantec|Sophos|Trend Micro|McAfee|Avira|F-Secure|Malwarebytes|Zscaler|Netskope|Fortinet|FortiGate|Palo Alto|Cisco Umbrella|Portmaster|Safing|GlassWire|NordVPN|AdGuard|NetFilter", RegexOptions.IgnoreCase), Severity.Info,
            "Security, VPN or filtering software inspects HTTPS traffic with this certificate. Expected if you use that product."),
    };

    /// <summary>
    /// Roots Windows ships itself (they are part of the OS image, not of the auto-updated AuthRoot list), so they
    /// can be missing from that list on fresh, offline or sandboxed installs.
    /// </summary>
    internal static readonly HashSet<string> WindowsBuiltInRoots = new(StringComparer.OrdinalIgnoreCase)
    {
        "245C97DF7514E7CF2DF8BE72AE957B9E04741E85", // Copyright (c) 1997 Microsoft Corp. (Time Stamping Service Root)
        "7F88CD7223F3C813818C994614A89C99FA3B5247", // Microsoft Authenticode(tm) Root Authority
        "06F1AA330B927B753A40E68CDF22E34BCBEF3352", // Microsoft ECC Product Root Certificate Authority 2018
        "31F9FC8BA3805986B721EA7295C65B3A44534274", // Microsoft ECC TS Root Certificate Authority 2018
        "A43489159A520F0D93D032CCAF37E7FE20A8B419", // Microsoft Root Authority
        "CDD4EEAE6000AC7F40C3802C171E30148030C072", // Microsoft Root Certificate Authority
        "3B1EFD3A66EA28B16697394703A72CA340A05BD5", // Microsoft Root Certificate Authority 2010
        "8F43288AD272F3103B6FB1428485EA3014C0BCFE", // Microsoft Root Certificate Authority 2011
        "0119E81BE9A14CD8E22F40AC118C687ECBA3F4D8", // Microsoft Time Stamp Root Certificate Authority 2014
        "18F7C1FCC3090203FD5BAA2F861A754976C8DD25", // VeriSign Time Stamping Service Root ("NO LIABILITY ACCEPTED")
        "BE36A4562FB2EE05DBB3D32323ADF445084ED656", // Thawte Timestamping CA
        "D1EB23A46D17D68FD92564C2F1F1601764D8E349", // AAA Certificate Services (Sectigo/Comodo public root)
    };

    public object? Run(CheckContext ctx)
    {
        var trusted = MicrosoftTrustedRoots(out var ctlSource);
        foreach (var t in WindowsBuiltInRoots) trusted.Add(t);
        // A real AuthRoot list has several hundred entries. If we only found a handful, the list is missing (offline or
        // sandboxed PC): don't call every root "unknown", say we couldn't check instead.
        if (ctlSource != "none" && trusted.Count < 150) { CheckContext.Note($"Microsoft's trusted root list looks incomplete ({trusted.Count} entries), so unknown roots weren't judged"); ctlSource = "none"; }
        else if (ctlSource == "none") CheckContext.Note("Microsoft's trusted root list couldn't be read, so unknown roots weren't judged");
        var machine = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var rows = new List<object>();
        void Inspect(X509Certificate2 c, string store)
        {
            var thumb = c.Thumbprint.ToUpperInvariant();
            // The current user's Root store also shows every machine root; report each certificate once, where it really is.
            if (store == "Machine") machine.Add(thumb); else if (machine.Contains(thumb)) return;
            bool ms = trusted.Contains(thumb);
            var subject = c.GetNameInfo(X509NameType.SimpleName, false);
            var known = Known.FirstOrDefault(k => k.Pattern.IsMatch(c.Subject));
            string risk = ms ? Risk.Info : known.Pattern is not null ? known.Sev.ToString() : store.StartsWith("User") ? Risk.High : Risk.Medium;
            rows.Add(new { Risk = risk, Store = store, Subject = subject, Issuer = c.GetNameInfo(X509NameType.SimpleName, true), Thumbprint = thumb,
                           NotBefore = c.NotBefore.ToString("yyyy-MM-dd"), NotAfter = c.NotAfter.ToString("yyyy-MM-dd"), MicrosoftTrusted = ms });
            if (ms) return;
            var ev = new { Store = store, Subject = c.Subject, Thumbprint = thumb, Added = c.NotBefore.ToString("s"), Expires = c.NotAfter.ToString("s") };
            if (known.Pattern is not null)
            {
                if (known.Sev == Severity.Info) return;
                ctx.Add(known.Sev, "Certificates", $"Extra trusted root certificate: {subject}", $"{known.Why}\nStore: {store}\nThumbprint: {thumb}",
                        "Remove it in certmgr.msc › Trusted Root Certification Authorities unless you know why it is there.", ev, "T1553.004", "cert.known-root");
            }
            else if (ctlSource != "none")
                ctx.Add(UnknownRootSeverity(store, subject, c.NotBefore), "Certificates", $"Unknown trusted root certificate: {subject}",
                        $"This root isn't on Microsoft's trusted list. Whoever owns it could impersonate any website to this PC.\nStore: {store}\nIssued: {c.NotBefore:yyyy-MM-dd}\nThumbprint: {thumb}",
                        "If your company or a security product didn't install it, remove it (certmgr.msc › Trusted Root Certification Authorities).", ev, "T1553.004", "cert.unknown-root");
        }

        foreach (var (name, loc) in new[] { ("Machine", StoreLocation.LocalMachine), ("User (current)", StoreLocation.CurrentUser) })
        {
            try
            {
                using var st = new X509Store(StoreName.Root, loc);
                st.Open(OpenFlags.ReadOnly | OpenFlags.OpenExistingOnly);
                foreach (var c in st.Certificates) using (c) Inspect(c, name);
            }
            catch { }
        }
        // Other signed-in users' personal root stores (registry blobs).
        var me = System.Security.Principal.WindowsIdentity.GetCurrent().User?.Value;
        foreach (var sid in Reg.LoadedUserSids().Where(s => s != me))
            foreach (var cert in UserRootBlobs(sid)) using (cert) Inspect(cert, $"User {sid}");

        return new { MicrosoftList = ctlSource, MicrosoftRoots = trusted.Count, Certificates = rows };
    }

    /// <summary>
    /// Unknown roots are common on home PCs (company VPNs, old tools), so most are Low. Medium when it looks like an
    /// attacker's: a random-looking name, added in the last 90 days, or in a user's personal store.
    /// </summary>
    internal static Severity UnknownRootSeverity(string store, string subject, DateTime notBefore)
    {
        bool randomName = Regex.IsMatch(subject, @"^(?=.*\d)(?=.*[a-z])(?=.*[A-Z])[A-Za-z0-9]{8,}$");
        bool recent = notBefore > DateTime.Now.AddDays(-90);
        return store.StartsWith("User") || randomName || recent ? Severity.Medium : Severity.Low;
    }

    /// <summary>Thumbprints in Microsoft's AuthRoot certificate trust list (auto-updated by Windows).</summary>
    internal static HashSet<string> MicrosoftTrustedRoots(out string source)
    {
        var set = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        source = "none";
        foreach (var (key, value) in new[] { (@"SOFTWARE\Microsoft\SystemCertificates\AuthRoot\AutoUpdate", "EncodedCtl"), (@"SOFTWARE\Policies\Microsoft\SystemCertificates\AuthRoot\AutoUpdate", "EncodedCtl") })
        {
            if (Reg.Value(Registry.LocalMachine, key, value) is not byte[] blob) continue;
            try { foreach (var t in ParseCtl(blob)) set.Add(t); source = "AuthRoot CTL"; } catch { }
        }
        // Certificates in the AuthRoot store were placed there by Windows Update from that same list.
        try
        {
            using var st = new X509Store("AuthRoot", StoreLocation.LocalMachine);
            st.Open(OpenFlags.ReadOnly | OpenFlags.OpenExistingOnly);
            foreach (var c in st.Certificates) using (c) set.Add(c.Thumbprint);
            if (source == "none" && set.Count > 0) source = "AuthRoot store";
        }
        catch { }
        return set;
    }

    internal static IEnumerable<string> ParseCtl(byte[] encoded)
    {
        var cms = new SignedCms();
        cms.Decode(encoded);
        var found = new List<string>();
        Walk(cms.ContentInfo.Content, found, 0);
        return found;
    }

    /// <summary>Collects every 20-byte OCTET STRING (SHA-1 thumbprints) in a DER structure.</summary>
    internal static void Walk(ReadOnlyMemory<byte> der, List<string> found, int depth)
    {
        if (depth > 12) return;
        var span = der;
        while (span.Length > 0)
        {
            Asn1Tag tag; int contentOffset, contentLength, consumed;
            try
            {
                tag = Asn1Tag.Decode(span.Span, out _);
                AsnDecoder.ReadEncodedValue(span.Span, AsnEncodingRules.DER, out contentOffset, out contentLength, out consumed);
            }
            catch { return; }
            var content = span.Slice(contentOffset, contentLength);
            if (tag.IsConstructed) Walk(content, found, depth + 1);
            else if (tag.TagClass == TagClass.Universal && tag.TagValue == (int)UniversalTagNumber.OctetString && contentLength == 20)
                found.Add(Convert.ToHexString(content.Span));
            span = span.Slice(consumed);
        }
    }

    /// <summary>Certificates in HKU\SID\...\SystemCertificates\Root\Certificates (property blob format, cert = property 0x20).</summary>
    private static IEnumerable<X509Certificate2> UserRootBlobs(string sid)
    {
        var list = new List<X509Certificate2>();
        var path = $@"{sid}\Software\Microsoft\SystemCertificates\Root\Certificates";
        foreach (var thumb in Reg.SubKeys(Registry.Users, path))
        {
            if (Reg.Value(Registry.Users, $@"{path}\{thumb}", "Blob") is not byte[] b) continue;
            int i = 0;
            while (i + 12 <= b.Length)
            {
                int id = BitConverter.ToInt32(b, i), len = BitConverter.ToInt32(b, i + 8);
                if (len < 0 || i + 12 + len > b.Length) break;
                if (id == 0x20) { try { list.Add(new X509Certificate2(b.AsSpan(i + 12, len).ToArray())); } catch { } break; }
                i += 12 + len;
            }
        }
        return list;
    }
}

/// <summary>Loaded kernel drivers: unsigned drivers, test-signing mode, and drivers attackers abuse to kill antivirus (BYOVD).</summary>
[SupportedOSPlatform("windows")]
public sealed class DriverCheck : ICheck
{
    public string Name => "Drivers";

    /// <summary>File names of signed drivers with public exploits used to disable security software (from LOLDrivers / Microsoft's blocklist).</summary>
    private static readonly Dictionary<string, string> Vulnerable = new(StringComparer.OrdinalIgnoreCase)
    {
        ["RTCore64.sys"] = "MSI Afterburner / RivaTuner", ["RTCore32.sys"] = "MSI Afterburner", ["gdrv.sys"] = "Gigabyte tools", ["dbutil_2_3.sys"] = "Dell BIOS utility",
        ["AsrDrv101.sys"] = "ASRock utility", ["AsrDrv102.sys"] = "ASRock utility", ["AsrDrv103.sys"] = "ASRock utility", ["AsrDrv104.sys"] = "ASRock utility", ["AsrDrv106.sys"] = "ASRock utility",
        ["iqvw64e.sys"] = "Intel network diagnostics", ["WinRing0x64.sys"] = "Hardware monitoring / fan control tools", ["WinRing0.sys"] = "Hardware monitoring tools",
        ["mhyprot2.sys"] = "Genshin Impact anti-cheat (old)", ["mhyprot.sys"] = "miHoYo anti-cheat (old)", ["Capcom.sys"] = "Capcom anti-cheat (old)",
        ["ene.sys"] = "RGB lighting software", ["AsIO.sys"] = "ASUS utilities", ["AsIO2.sys"] = "ASUS utilities", ["AsIO3.sys"] = "ASUS utilities",
        ["NTIOLib_X64.sys"] = "MSI utilities", ["HwRwDrv.sys"] = "Hardware read/write utility", ["speedfan.sys"] = "SpeedFan", ["inpoutx64.sys"] = "InpOut port I/O library",
        ["ATSZIO64.sys"] = "ASUS ATSZ utility", ["BS_RCIO64.sys"] = "Biostar utility", ["GLCKIO2.sys"] = "ASRock/Gigabyte RGB", ["AODDriver2.sys"] = "AMD OverDrive (old)",
        ["amifldrv64.sys"] = "AMI BIOS flash tool", ["kprocesshacker.sys"] = "Process Hacker (old driver)", ["PhyMemx64.sys"] = "Physical memory access tool",
        ["cpuz141_x64.sys"] = "CPU-Z (old)", ["LHA.sys"] = "LG utility", ["Bs_Def64.sys"] = "Biostar utility", ["procexp152.sys"] = "Process Explorer (old version)",
        ["zam64.sys"] = "Zemana/Malwarebytes (old)", ["Monitor_win10_x64.sys"] = "Hardware monitoring", ["PDFWKRNL.sys"] = "AMD uProf (old)", ["truesight.sys"] = "Adlice RogueKiller (old)",
    };

    public object? Run(CheckContext ctx)
    {
        var rows = new List<object>();
        var opts = Reg.Value(Registry.LocalMachine, @"SYSTEM\CurrentControlSet\Control", "SystemStartOptions") as string ?? "";
        if (Regex.IsMatch(opts, @"TESTSIGNING|DISABLE_INTEGRITY_CHECKS", RegexOptions.IgnoreCase))
            ctx.Add(Severity.High, "Drivers", "Driver signature enforcement is weakened (test signing / integrity checks off)", $"Boot options: {opts.Trim()}",
                    "Unless you develop drivers, turn it off: bcdedit /set testsigning off (as admin) and restart.", new { BootOptions = opts }, "T1553.006", "driver.testsigning");
        var blocklist = Reg.Value(Registry.LocalMachine, @"SYSTEM\CurrentControlSet\Control\CI\Config", "VulnerableDriverBlocklistEnable");
        if (blocklist is int bl && bl == 0)
            ctx.Add(Severity.Low, "Drivers", "Microsoft's vulnerable driver blocklist is off", "Windows normally blocks drivers that attackers are known to abuse.",
                    "Turn it on in Windows Security › Device security › Core isolation › Microsoft Vulnerable Driver Blocklist.", ruleId: "driver.blocklist-off");

        foreach (var d in Wmi.Query("SELECT Name, DisplayName, PathName, State, StartMode FROM Win32_SystemDriver WHERE State='Running'"))
        {
            var path = Normalize(d.S("PathName"));
            if (path is null) continue;
            var intel = ctx.Files.Get(path);
            var file = Path.GetFileName(path);
            var vuln = Vulnerable.TryGetValue(file, out var by) ? by : null;
            var risk = vuln is not null ? Risk.Medium : intel is { Exists: true, IsSigned: false } ? Risk.High : Risk.Info;
            rows.Add(new { Risk = risk, Name = d.S("Name"), Display = d.S("DisplayName"), Path = path, Signer = intel?.Signer, Signature = intel?.SignatureStatus.ToString(), KnownVulnerable = vuln });
            if (vuln is not null)
                ctx.Add(Severity.Medium, "Drivers", $"Known-vulnerable driver loaded: {file}", $"Used by: {vuln}\n{path}\nAttackers who get admin rights can abuse this signed driver to switch off antivirus (\"bring your own vulnerable driver\").",
                        "Update or uninstall the tool that installed it, and turn on Microsoft's Vulnerable Driver Blocklist.", new { Driver = file, Path = path, UsedBy = vuln, intel?.SHA256 }, "T1068", "driver.vulnerable");
            else if (intel is { Exists: true, IsSigned: false } && intel.SignatureStatus != SignatureStatus.Unknown)
                ctx.Add(Severity.High, "Drivers", $"Unsigned kernel driver running: {file}", $"{path}\nSignature: {intel.SignatureStatus}",
                        "Kernel drivers have full control of the PC. Find out which program installed it; rootkits often use unsigned drivers.", new { Path = path, intel.SHA256 }, "T1014", "driver.unsigned");
        }
        return new { BootOptions = opts.Trim(), Drivers = rows };
    }

    internal static string? Normalize(string? p)
    {
        if (string.IsNullOrWhiteSpace(p)) return null;
        p = p.Trim().Trim('"');
        if (p.StartsWith(@"\??\")) p = p[4..];
        if (p.StartsWith(@"\SystemRoot\", StringComparison.OrdinalIgnoreCase)) p = Path.Combine(Sys.SystemRoot, p[12..]);
        else if (p.StartsWith(@"System32\", StringComparison.OrdinalIgnoreCase)) p = Path.Combine(Sys.SystemRoot, p);
        else if (p.StartsWith("%")) p = Environment.ExpandEnvironmentVariables(p);
        return p;
    }
}

/// <summary>Which apps used the camera, microphone and location (Windows keeps this record per user).</summary>
[SupportedOSPlatform("windows")]
public sealed class PrivacyCheck : ICheck
{
    public string Name => "Camera, microphone & location";

    public object? Run(CheckContext ctx)
    {
        var rows = new List<Row>();
        var users = Sys.UserProfiles().ToDictionary(u => u.Sid, u => u.Name);
        foreach (var sid in Reg.LoadedUserSids())
            foreach (var cap in new[] { "webcam", "microphone", "location" })
            {
                var basePath = $@"{sid}\Software\Microsoft\Windows\CurrentVersion\CapabilityAccessManager\ConsentStore\{cap}";
                foreach (var app in Reg.SubKeys(Registry.Users, basePath))
                {
                    if (app.Equals("NonPackaged", StringComparison.OrdinalIgnoreCase))
                    {
                        foreach (var np in Reg.SubKeys(Registry.Users, $@"{basePath}\NonPackaged"))
                            Add(rows, sid, users, cap, np.Replace('#', '\\'), $@"{basePath}\NonPackaged\{np}", packaged: false);
                    }
                    else Add(rows, sid, users, cap, app, $@"{basePath}\{app}", packaged: true);
                }
            }

        string Cap(string c) => c switch { "webcam" => "camera", "microphone" => "microphone", _ => "location" };
        foreach (var r in rows.Where(r => r.InUse))
            ctx.Add(Severity.Info, "Privacy", $"{r.App} is using the {Cap(r.Capability)} right now", r.Path ?? r.App, "If you didn't expect this, close the app.", r, ruleId: "privacy.in-use");
        foreach (var r in rows.Where(r => !r.Packaged && r.Path is not null && r.LastUsed is not null))
        {
            if (!File.Exists(r.Path)) continue;
            var intel = ctx.Files.Get(r.Path);
            if (intel is { IsSigned: false } && PathHeuristics.IsUserWritable(r.Path) && r.Capability != "location")
                ctx.Add(Severity.High, "Privacy", $"Unsigned program used your {Cap(r.Capability)}: {Path.GetFileName(r.Path)}", $"{r.Path}\nLast used: {r.LastUsed}",
                        "Spyware and remote-access trojans record through the camera and microphone. If you don't recognise this program, investigate it now.", r, "T1125", "privacy.unsigned-capture");
        }
        var recent = rows.Where(r => r.LastUsed is not null && r.Capability != "location").OrderByDescending(r => r.LastUsed).Take(6).ToList();
        if (recent.Count > 0)
            ctx.Add(Severity.Info, "Privacy", "Apps that recently used your camera or microphone",
                    string.Join("\n", recent.Select(r => $"{r.App} – {Cap(r.Capability)}, {r.LastUsed}")), "Review these in Settings › Privacy & security › Camera / Microphone.", recent, ruleId: "privacy.recent");
        return new { Usage = rows.OrderByDescending(r => r.LastUsed).ToList() };
    }

    private static void Add(List<Row> rows, string sid, Dictionary<string, string> users, string cap, string app, string key, bool packaged)
    {
        DateTime? Ft(string name) => Reg.Value(Registry.Users, key, name) is long v && v > 0 ? DateTime.FromFileTime(v) : null;
        var start = Ft("LastUsedTimeStart");
        var stop = Reg.Value(Registry.Users, key, "LastUsedTimeStop") is long s ? s : -1;
        var name = packaged ? Regex.Replace(app, @"_[a-z0-9]{13}$", "") : Path.GetFileNameWithoutExtension(app);
        rows.Add(new Row(users.GetValueOrDefault(sid, sid), cap, name, packaged ? null : app, packaged, start?.ToString("yyyy-MM-dd HH:mm"), start is not null && stop == 0));
    }

    public sealed record Row(string User, string Capability, string App, string? Path, bool Packaged, string? LastUsed, bool InUse) { public string Risk => InUse ? "Low" : "Info"; }
}

/// <summary>Advanced Windows hardening not covered by the posture check.</summary>
[SupportedOSPlatform("windows")]
public sealed class HardeningCheck : ICheck
{
    public string Name => "Windows hardening";

    public object? Run(CheckContext ctx)
    {
        var data = new Dictionary<string, object?>();
        var dg = Wmi.Query("SELECT VirtualizationBasedSecurityStatus, SecurityServicesRunning FROM Win32_DeviceGuard", @"root\Microsoft\Windows\DeviceGuard").FirstOrDefault();
        if (dg is not null)
        {
            var running = dg.A("SecurityServicesRunning");
            bool hvci = running.Contains("2"), credGuard = running.Contains("1");
            data["VBS"] = dg.L("VirtualizationBasedSecurityStatus"); data["MemoryIntegrity"] = hvci; data["CredentialGuard"] = credGuard;
            if (!hvci) ctx.Add(Severity.Low, "Hardening", "Memory integrity (core isolation) is off", "It stops malicious or vulnerable drivers from tampering with Windows' core.",
                               "Turn it on in Windows Security › Device security › Core isolation (restart needed; check that your drivers are compatible).", ruleId: "harden.hvci-off");
        }
        var ppl = Reg.Value(Registry.LocalMachine, @"SYSTEM\CurrentControlSet\Control\Lsa", "RunAsPPL");
        data["LsaProtection"] = ppl;
        if (ppl is not int p || p == 0)
            ctx.Add(Severity.Low, "Hardening", "Local Security Authority protection is off", "Password-stealing tools (like Mimikatz) can read sign-in secrets from memory.",
                    "Turn on 'Local Security Authority protection' in Windows Security › Device security › Core isolation.", mitre: "T1003.001", ruleId: "harden.lsa-ppl-off");

        var smb1 = Reg.Value(Registry.LocalMachine, @"SYSTEM\CurrentControlSet\Services\LanmanServer\Parameters", "SMB1");
        var mrx = Reg.Value(Registry.LocalMachine, @"SYSTEM\CurrentControlSet\Services\mrxsmb10", "Start");
        bool smb1On = (smb1 is int s1 && s1 == 1) || (mrx is int m && m != 4);
        data["SMBv1"] = smb1On;
        if (smb1On) ctx.Add(Severity.Medium, "Hardening", "The outdated SMBv1 file-sharing protocol is enabled", "SMBv1 was used by the WannaCry and NotPetya worms.",
                            "Turn it off: Control Panel › Programs › Turn Windows features on or off › uncheck 'SMB 1.0/CIFS File Sharing Support'.", mitre: "T1210", ruleId: "harden.smb1");

        var rdpOn = Reg.Value(Registry.LocalMachine, @"SYSTEM\CurrentControlSet\Control\Terminal Server", "fDenyTSConnections") is int d && d == 0;
        var nla = Reg.Value(Registry.LocalMachine, @"SYSTEM\CurrentControlSet\Control\Terminal Server\WinStations\RDP-Tcp", "UserAuthentication");
        data["RdpNla"] = nla;
        if (rdpOn && nla is int n && n == 0)
            ctx.Add(Severity.Medium, "Hardening", "Remote Desktop allows connections without Network Level Authentication", "Attackers can reach the Windows sign-in screen before proving who they are.",
                    "Settings › System › Remote Desktop › Advanced settings › require Network Level Authentication.", mitre: "T1021.001", ruleId: "harden.rdp-nla");

        var ps2 = Reg.Value(Registry.LocalMachine, @"SOFTWARE\Microsoft\PowerShell\1\PowerShellEngine", "PowerShellVersion") as string;
        data["PowerShell2"] = ps2;
        if (ps2 is not null && ps2.StartsWith("2."))
            ctx.Add(Severity.Low, "Hardening", "PowerShell 2.0 is installed", "Attackers use this old version to bypass PowerShell's security logging and AMSI.",
                    "Remove it: Turn Windows features on or off › uncheck 'Windows PowerShell 2.0'.", mitre: "T1562.010", ruleId: "harden.ps2");

        var tpm = Wmi.Query("SELECT IsEnabled_InitialValue, IsActivated_InitialValue, SpecVersion FROM Win32_Tpm", @"root\CIMV2\Security\MicrosoftTpm").FirstOrDefault();
        data["TPM"] = tpm is null ? null : new { Enabled = tpm.B("IsEnabled_InitialValue"), Spec = tpm.S("SpecVersion") };
        if (ctx.Options.Elevated && tpm is null)
            ctx.Add(Severity.Low, "Hardening", "No TPM security chip detected", "The TPM protects BitLocker keys, Windows Hello and other secrets.",
                    "Enable TPM / fTPM / PTT in your PC's firmware (BIOS) settings if available.", ruleId: "harden.no-tpm");

        var pref = Wmi.Query("SELECT AttackSurfaceReductionRules_Ids, AttackSurfaceReductionRules_Actions FROM MSFT_MpPreference", @"root\Microsoft\Windows\Defender").FirstOrDefault();
        if (pref is not null)
        {
            var ids = pref.A("AttackSurfaceReductionRules_Ids"); var acts = pref.A("AttackSurfaceReductionRules_Actions");
            int active = acts.Count(a => a is "1" or "6");
            data["AsrRulesActive"] = active;
            if (active == 0)
                ctx.Add(Severity.Info, "Hardening", "Defender attack surface reduction rules are not in use", "These optional rules block common attack tricks (Office macros starting programs, credential theft, etc.).",
                        "Advanced users can turn on the recommended rules with a tool such as ConfigureDefender.", ruleId: "harden.asr-none");
            else
            {
                int idx = Array.FindIndex(ids, i => i.Equals("01443614-cd74-4a2e-b6f0-ec80e5f07d63", StringComparison.OrdinalIgnoreCase));
                if (idx >= 0 && idx < acts.Length && acts[idx] == "1")
                    ctx.Add(Severity.Info, "Hardening", "Strict ASR rule is on: new, unknown programs are blocked", "Good protection. Note that it also blocks new legitimate tools until they are widely used.",
                            "Allow trusted new programs with an ASR-only exclusion rather than turning protection off.", ruleId: "harden.asr-prevalence");
            }
        }
        return data;
    }
}

/// <summary>Less common persistence and hijack locations, plus local accounts.</summary>
[SupportedOSPlatform("windows")]
public sealed class HiddenPersistenceCheck : ICheck
{
    public string Name => "Hidden persistence & accounts";

    private static readonly HashSet<string> DefaultLsa = new(StringComparer.OrdinalIgnoreCase)
    { "msv1_0", "kerberos", "schannel", "wdigest", "tspkg", "pku2u", "cloudap", "negoexts", "livessp", "scecli", "rassfm", "\"\"", "" };

    public object? Run(CheckContext ctx)
    {
        var rows = new List<object>();
        string sys32 = Path.Combine(Sys.SystemRoot, "System32");
        string? Dll(string name) { if (string.IsNullOrWhiteSpace(name)) return null; var n = Environment.ExpandEnvironmentVariables(name.Trim('"')); if (!Path.IsPathRooted(n)) n = Path.Combine(sys32, n.EndsWith(".dll", StringComparison.OrdinalIgnoreCase) ? n : n + ".dll"); return n; }
        bool NotMicrosoft(string? path, out FileIntel? fi) { fi = path is null ? null : ctx.Files.Get(path); return fi is { Exists: true } && !fi.IsMicrosoft; }

        // LSA packages: loaded into lsass, the process holding sign-in secrets.
        foreach (var v in new[] { "Security Packages", "Authentication Packages", "Notification Packages" })
            foreach (var key in new[] { @"SYSTEM\CurrentControlSet\Control\Lsa", @"SYSTEM\CurrentControlSet\Control\Lsa\OSConfig" })
                if (Reg.Value(Registry.LocalMachine, key, v) is string[] pkgs)
                    foreach (var pkg in pkgs.Where(x => !DefaultLsa.Contains(x)))
                    {
                        var path = Dll(pkg);
                        rows.Add(new { Type = "LSA package", Location = $@"HKLM\{key}\{v}", Value = pkg, Path = path });
                        if (NotMicrosoft(path, out var fi))
                            ctx.Add(fi!.IsSigned ? Severity.Medium : Severity.High, "Persistence", $"Non-Microsoft module loaded into the sign-in process (LSA): {pkg}", $"{path}\nSigner: {fi.Signer ?? "unsigned"}",
                                    "Password managers or smart-card software can add these legitimately. If you don't recognise it, treat it as a password stealer.", new { pkg, path, fi.Signer }, "T1547.002", "persist.lsa-package");
                    }

        // AppCertDlls: loaded into every process that creates processes.
        foreach (var (n, v) in Reg.Values(Registry.LocalMachine, @"SYSTEM\CurrentControlSet\Control\Session Manager\AppCertDlls"))
        {
            var path = Dll(v?.ToString() ?? ""); rows.Add(new { Type = "AppCertDlls", Value = n, Path = path });
            ctx.Add(Severity.High, "Persistence", $"AppCertDlls entry: {n}", $"{path}\nThis DLL is loaded into many programs. It is almost never used legitimately.",
                    "Investigate and remove it if you don't know what installed it.", new { n, path }, "T1546.009", "persist.appcertdlls");
        }

        // Netsh helper DLLs.
        foreach (var (n, v) in Reg.Values(Registry.LocalMachine, @"SOFTWARE\Microsoft\NetSh"))
        {
            var path = Dll(v?.ToString() ?? "");
            if (NotMicrosoft(path, out var fi))
            {
                rows.Add(new { Type = "Netsh helper", Value = n, Path = path, fi!.Signer });
                ctx.Add(fi.IsSigned ? Severity.Low : Severity.High, "Persistence", $"Non-Microsoft netsh helper: {Path.GetFileName(path)}", $"{path}\nSigner: {fi.Signer ?? "unsigned"}",
                        "VPN software sometimes adds these. Otherwise it's a known persistence trick.", new { n, path }, "T1546.007", "persist.netsh");
            }
        }

        // Print monitors (loaded by the print spooler as SYSTEM).
        foreach (var mon in Reg.SubKeys(Registry.LocalMachine, @"SYSTEM\CurrentControlSet\Control\Print\Monitors"))
        {
            var drv = Reg.Value(Registry.LocalMachine, $@"SYSTEM\CurrentControlSet\Control\Print\Monitors\{mon}", "Driver") as string;
            var path = drv is null ? null : Dll(drv);
            if (path is not null && NotMicrosoft(path, out var fi) && !fi!.IsSigned)
            {
                rows.Add(new { Type = "Print monitor", Value = mon, Path = path });
                ctx.Add(Severity.High, "Persistence", $"Unsigned print monitor: {mon}", path, "Unsigned DLLs loaded by the print spooler run as SYSTEM. Investigate it.", new { mon, path }, "T1547.010", "persist.print-monitor");
            }
        }

        // Accessibility tools replaced (sticky-keys backdoor).
        foreach (var exe in new[] { "sethc.exe", "utilman.exe", "osk.exe", "Magnify.exe", "Narrator.exe", "DisplaySwitch.exe", "AtBroker.exe" })
        {
            var path = Path.Combine(sys32, exe);
            if (!File.Exists(path)) continue;
            var fi = ctx.Files.Get(path);
            if (fi is { Exists: true } && !fi.IsMicrosoft && fi.SignatureStatus != SignatureStatus.Unknown)
                ctx.Add(Severity.Critical, "Persistence", $"Accessibility tool replaced: {exe}", $"{path} is not Microsoft's file (signature: {fi.SignatureStatus}, signer: {fi.Signer ?? "none"}).",
                        "This is the classic 'sticky keys' backdoor that opens a SYSTEM command prompt at the sign-in screen. Treat the PC as compromised.", new { path, fi.SHA256 }, "T1546.008", "persist.accessibility");
        }

        // COM hijacking in user hives: a per-user CLSID overrides the system one.
        foreach (var sid in Reg.LoadedUserSids())
        {
            var root = $@"{sid}_Classes\CLSID";
            foreach (var clsid in Reg.SubKeys(Registry.Users, root))
                foreach (var server in new[] { "InprocServer32", "LocalServer32" })
                {
                    if (Reg.Value(Registry.Users, $@"{root}\{clsid}\{server}", "") is not string raw || raw.Length == 0) continue;
                    var path = CommandLine.ExtractTarget(raw, Environment.ExpandEnvironmentVariables, Sys.ResolveProgram) ?? raw.Trim('"');
                    if (!PathHeuristics.IsUserWritable(path) || !File.Exists(path)) continue;
                    var fi = ctx.Files.Get(path);
                    if (fi is { IsSigned: false })
                    {
                        rows.Add(new { Type = "COM object (user)", Value = clsid, Path = path });
                        ctx.Add(Severity.High, "Persistence", $"Unsigned COM object registered for one user: {Path.GetFileName(path)}", $"CLSID {clsid}\n{path}",
                                "Per-user COM registrations pointing to unsigned files in user folders are a common way to hijack Windows components.", new { clsid, path, fi.SHA256 }, "T1546.015", "persist.com-hijack");
                    }
                }
        }

        // Browser policies: force-installed extensions and search hijacks (adware sets these on home PCs).
        var policyRoots = new List<(RegistryKey Root, string Prefix, string Label)> { (Registry.LocalMachine, "", "HKLM") };
        foreach (var sid in Reg.LoadedUserSids()) policyRoots.Add((Registry.Users, sid + @"\", $"HKU\\{sid}"));
        foreach (var (hive, prefix, label) in policyRoots)
            foreach (var (browser, key) in new[] { ("Chrome", @"SOFTWARE\Policies\Google\Chrome"), ("Edge", @"SOFTWARE\Policies\Microsoft\Edge"), ("Brave", @"SOFTWARE\Policies\BraveSoftware\Brave") })
            {
                foreach (var (_, v) in Reg.Values(hive, $@"{prefix}{key}\ExtensionInstallForcelist"))
                {
                    var entry = v?.ToString() ?? ""; var id = entry.Split(';')[0];
                    var url = entry.Contains(';') ? entry[(entry.IndexOf(';') + 1)..] : "";
                    bool storeUrl = url.Length == 0 || Regex.IsMatch(url, @"^https://(clients2\.google\.com|edge\.microsoft\.com)/", RegexOptions.IgnoreCase);
                    rows.Add(new { Type = $"{browser} forced extension", Value = id, Path = url, Location = label });
                    ctx.Add(storeUrl ? Severity.Medium : Severity.High, "Browser", $"{browser} extension force-installed by policy: {id}", $"{label}\\{key}\\ExtensionInstallForcelist\nUpdate URL: {(url.Length == 0 ? "store" : url)}",
                            "You can't remove a force-installed extension yourself. On a home PC this is usually adware; delete the policy entry or ask your IT department.", new { browser, id, url, label }, "T1176", "browser.forced-extension");
                }
                var search = Reg.Value(hive, $@"{prefix}{key}", "DefaultSearchProviderSearchURL") as string;
                if (!string.IsNullOrEmpty(search))
                    ctx.Add(Severity.Medium, "Browser", $"{browser} search engine is locked by policy", $"{label}\\{key}\nSearch URL: {search}",
                            "Search hijackers set this so you can't change it back. Remove the policy unless your organisation set it.", new { browser, search, label }, "T1176", "browser.search-policy");
            }

        // PowerShell profiles run on every PowerShell start.
        var profiles = new List<string> { Path.Combine(sys32, @"WindowsPowerShell\v1.0\profile.ps1"), Path.Combine(sys32, @"WindowsPowerShell\v1.0\Microsoft.PowerShell_profile.ps1") };
        foreach (var u in Sys.UserProfiles())
            foreach (var sub in new[] { @"Documents\WindowsPowerShell", @"Documents\PowerShell", @"OneDrive\Documents\WindowsPowerShell", @"OneDrive\Documents\PowerShell" })
                foreach (var f in new[] { "profile.ps1", "Microsoft.PowerShell_profile.ps1" }) profiles.Add(Path.Combine(u.Path, sub, f));
        foreach (var p in profiles.Where(File.Exists))
        {
            rows.Add(new { Type = "PowerShell profile", Path = p });
            string text = ""; try { text = File.ReadAllText(p); } catch { }
            bool suspicious = CommandLine.IsSuspiciousScriptHost(text) || Regex.IsMatch(text, @"DownloadString|IEX|Invoke-Expression|FromBase64String|Net\.WebClient", RegexOptions.IgnoreCase);
            ctx.Add(suspicious ? Severity.High : Severity.Low, "Persistence", $"PowerShell profile {(suspicious ? "with download/execute code" : "present")}: {Path.GetFileName(Path.GetDirectoryName(p))}\\{Path.GetFileName(p)}", p,
                    suspicious ? "This profile downloads or decodes code every time PowerShell starts. Review it now." : "Profiles run code on every PowerShell start. Make sure you created it.", new { p }, "T1546.013", "persist.ps-profile");
        }

        // Local accounts.
        var accounts = new List<object>();
        var hidden = Reg.Values(Registry.LocalMachine, @"SOFTWARE\Microsoft\Windows NT\CurrentVersion\Winlogon\SpecialAccounts\UserList").Where(x => x.Value is int i && i == 0).Select(x => x.Name).ToHashSet(StringComparer.OrdinalIgnoreCase);
        foreach (var a in Wmi.Query("SELECT Name, SID, Disabled, PasswordRequired, Lockout FROM Win32_UserAccount WHERE LocalAccount=True"))
        {
            var name = a.S("Name") ?? ""; var sid = a.S("SID") ?? ""; bool enabled = a.B("Disabled") == false;
            accounts.Add(new { Name = name, Sid = sid, Enabled = enabled, PasswordRequired = a.B("PasswordRequired"), Hidden = hidden.Contains(name) });
            if (!enabled) continue;
            if (sid.EndsWith("-501"))
                ctx.Add(Severity.Medium, "Accounts", "The Guest account is enabled", "Anyone can sign in to this PC without a password.", "Disable it: net user Guest /active:no (as admin).", ruleId: "account.guest");
            else if (sid.EndsWith("-500"))
                ctx.Add(Severity.Low, "Accounts", "The built-in Administrator account is enabled", "It is a well-known target for password guessing.", "Disable it unless you need it: net user Administrator /active:no.", ruleId: "account.builtin-admin");
            if (hidden.Contains(name))
                ctx.Add(Severity.High, "Accounts", $"Hidden user account: {name}", "This enabled account is hidden from the sign-in screen.", "Attackers hide backdoor accounts this way. Delete it if you didn't create it.", new { name, sid }, "T1564.002", "account.hidden");
            if (a.B("PasswordRequired") == false && !sid.EndsWith("-501"))
                // Common on home PCs (also with Microsoft accounts) and not proof of an empty password, so Low.
                ctx.Add(Severity.Low, "Accounts", $"Windows doesn't require a password for: {name}", "This account is allowed to have an empty password. That doesn't mean it has one; with a Microsoft account or PIN it is usually fine.", "If the account really has no password, set one (Settings > Accounts > Sign-in options).", new { name }, "T1078.003", "account.no-password");
        }
        return new { Items = rows, Accounts = accounts };
    }
}

/// <summary>Unsigned DLLs from user folders loaded into Microsoft processes (DLL injection / hijacking).</summary>
[SupportedOSPlatform("windows")]
public sealed class ModuleCheck : ICheck
{
    public string Name => "Loaded modules";
    public bool IsSlow => true;
    public int Order => 40;

    public object? Run(CheckContext ctx)
    {
        var rows = new List<object>();
        var self = Environment.ProcessId;
        foreach (var p in System.Diagnostics.Process.GetProcesses())
        {
            using (p)
            {
                if (ctx.Cancellation.IsCancellationRequested) break;
                if (p.Id <= 4 || p.Id == self) continue;
                string? exe; System.Diagnostics.ProcessModuleCollection mods;
                try { exe = p.MainModule?.FileName; mods = p.Modules; } catch { continue; }
                if (exe is null) continue;
                var host = ctx.Files.Get(exe, hash: false);
                if (host is not { IsMicrosoft: true }) continue;
                foreach (System.Diagnostics.ProcessModule m in mods)
                {
                    string? path; try { path = m.FileName; } catch { continue; }
                    if (path is null || !PathHeuristics.IsUserWritable(path)) continue;
                    var fi = ctx.Files.Get(path);
                    if (fi is not { Exists: true, IsSigned: false }) continue;
                    var name = Path.GetFileName(exe);
                    bool shell = name.Equals("explorer.exe", StringComparison.OrdinalIgnoreCase);
                    rows.Add(new { Risk = shell ? Risk.Medium : Risk.High, Process = name, PID = p.Id, Module = path, fi.SHA256 });
                    ctx.Add(shell ? Severity.Medium : Severity.High, "Processes", $"Unsigned DLL from a user folder loaded into {name}: {Path.GetFileName(path)}",
                            $"Process: {exe} (PID {p.Id})\nModule: {path}",
                            shell ? "Shell extensions can do this legitimately (e.g. cloud-storage tools). If you don't recognise it, investigate." : "Code injected into a Windows process is a classic malware technique. Check this file on VirusTotal.",
                            new { Process = exe, Module = path, fi.SHA256 }, "T1055.001", "process.injected-dll");
                }
            }
        }
        return new { Modules = rows };
    }
}

/// <summary>Deep scan (opt-in): malware rules across the user's folders, ProgramData and Program Files.</summary>
[SupportedOSPlatform("windows")]
public sealed class DeepFileScanCheck : ICheck
{
    public string Name => "Deep scan: all files";
    public bool IsSlow => true;
    public bool DeepOnly => true;
    public int Order => 85;
    private static readonly Regex Interesting = new(@"\.(exe|dll|scr|com|cpl|sys|ps1|psm1|vbs|vbe|js|jse|mjs|cjs|py|pyw|au3|ahk|hta|bat|cmd|wsf|lnk|zip|docm|xlsm|pptm|dotm|doc|xls)$", RegexOptions.IgnoreCase);
    private static readonly Regex SkipDirs = new(@"\\(WinSxS|Installer|\$Recycle\.Bin|node_modules|\.git|Windows\\servicing|Microsoft\\Edge\\Application|Google\\Chrome\\Application|steamapps\\common|Packages\\Microsoft\.|WindowsApps|dotnet\\packs|dotnet\\shared)\\", RegexOptions.IgnoreCase);

    public object? Run(CheckContext ctx)
    {
        var roots = new List<string> { Environment.GetFolderPath(Environment.SpecialFolder.CommonApplicationData), Environment.GetFolderPath(Environment.SpecialFolder.ProgramFiles),
                                       Environment.GetFolderPath(Environment.SpecialFolder.ProgramFilesX86), Environment.GetEnvironmentVariable("PUBLIC") ?? @"C:\Users\Public", Path.Combine(Sys.SystemRoot, "Temp") };
        roots.AddRange(Sys.UserProfiles().Select(u => u.Path));
        var targets = new List<string>(); int seen = 0;
        const int MaxTargets = 25000;
        int folders = 0;
        foreach (var root in roots.Where(Directory.Exists).Distinct(StringComparer.OrdinalIgnoreCase))
        {
            // Walked by hand so folders that never need checking (Windows component store, browser program folders,
            // node_modules, installed Steam games...) are skipped whole instead of being listed file by file.
            var stack = new Stack<DirectoryInfo>(); stack.Push(new DirectoryInfo(root));
            while (stack.Count > 0 && !ctx.Cancellation.IsCancellationRequested && targets.Count < MaxTargets)
            {
                var dir = stack.Pop();
                folders++;
                FileInfo[] files; DirectoryInfo[] subs;
                try { files = dir.GetFiles(); subs = dir.GetDirectories(); } catch { continue; }
                foreach (var sd in subs)
                {
                    try { if ((sd.Attributes & (FileAttributes.ReparsePoint | FileAttributes.Offline)) != 0) continue; } catch { continue; }
                    if (!SkipDirs.IsMatch(sd.FullName + "\\")) stack.Push(sd);
                }
                foreach (var f in files)
                {
                    if (targets.Count >= MaxTargets) break;
                    seen++;
                    if (seen % 2000 == 0) ctx.Log($"Deep scan: went through {seen:N0} files in {folders:N0} folders, {targets.Count:N0} programs and scripts to check…");
                    try
                    {
                        if (!Interesting.IsMatch(f.Name) || f.Length == 0) continue;   // excluded folders still scanned; Critical always shows
                        if ((f.Attributes & FileAttributes.Offline) != 0) continue;   // cloud-only (OneDrive): reading would download it
                        bool container = Regex.IsMatch(f.Name, @"\.(zip|docm|xlsm|pptm|dotm|doc|xls)$", RegexOptions.IgnoreCase);
                        if (f.Length > (container ? 200L : 32L) * 1024 * 1024) continue;
                        bool pe = Regex.IsMatch(f.Name, @"\.(exe|dll|scr|com|cpl|sys)$", RegexOptions.IgnoreCase);
                        if (pe) { var fi = ctx.Files.Get(f.FullName, hash: false); if (fi is { IsSigned: true }) continue; }   // signed binaries are skipped to keep the scan fast
                        targets.Add(f.FullName);
                    }
                    catch { }
                }
            }
        }
        if (targets.Count >= MaxTargets) CheckContext.Note($"Deep scan stopped collecting at {MaxTargets:N0} files to check");
        ctx.Log($"Deep scan: checking {targets.Count:N0} files with malware rules…");
        var inner = new TriageKit.Core.Yara.YaraCheck(Name, targets).Run(ctx);
        return new { FilesSeen = seen, Folders = folders, Targets = targets.Count, Capped = targets.Count >= MaxTargets, Result = inner };
    }
}
